#!/usr/bin/env bash
# Regenerates widget_card_shadow.xml, the transparent-background twin of widget_card.xml.
# RemoteViews cannot change a TextView's shadow at runtime, so the twin swaps the
# WidgetCardText styles for WidgetCardShadow styles that add one.
set -euo pipefail
LAYOUT="$(cd "$(dirname "$0")/.." && pwd)/app/src/main/res/layout"
{
  printf '<?xml version="1.0" encoding="utf-8"?>\n'
  printf '<!-- GENERATED by android/tools/widget-card-shadow.sh from widget_card.xml. Do not edit. -->\n'
  sed -e '1d' -e 's|@style/WidgetCardText\.|@style/WidgetCardShadow.|g' "$LAYOUT/widget_card.xml"
} > "$LAYOUT/widget_card_shadow.xml"
